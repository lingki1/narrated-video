# The colours of the ready-made character. The keys follow lib/buddy.js (its 2D self), plus what only exists here.
BUDDY_LOOK = {'body': '#26232B', 'outline': PAPER, 'limb': '#26232B', 'shoe': PINK, 'blush': PINK, 'eye': WHITE, 'pupil': INK, 'mouth': PAPER,
              'rim': None, 'card': WHITE, 'card_edge': INK, 'card_text': PINK}
_BUDDY_MATS = {}


def tones(hexstr, dark=0.6, lift=0.0):
    """the two flat tones a toon material needs, from one colour: (away from the sun, toward it)"""
    c = [int(hexstr.lstrip('#')[i:i + 2], 16) for i in (0, 2, 4)]
    as_hex = lambda v: '#' + ''.join(f'{max(0, min(255, round(x))):02X}' for x in v)
    return as_hex([x * dark for x in c]), as_hex([x + (255 - x) * lift for x in c])


def _buddy_mats(look):
    key = tuple(sorted(look.items()))
    if key not in _BUDDY_MATS:
        k = len(_BUDDY_MATS); tag = f'buddy{k}' if k else 'buddy'
        M = dict(body=toon(f'{tag}-body', *tones(look['body'], 0.6, 0.065), rim=look['rim']), limb=toon(f'{tag}-limb', *tones(look['limb'], 0.6, 0.065)),
                 line=flat(f'{tag}-outline', look['outline']), shoe=toon(f'{tag}-shoe', *tones(look['shoe'], 0.82)), blush=toon(f'{tag}-blush', *tones(look['blush'], 0.82)),
                 eye=flat(f'{tag}-eye', look['eye']), pupil=flat(f'{tag}-pupil', look['pupil']), mouth=toon(f'{tag}-mouth', *tones(look['mouth'], 0.8)),
                 card=flat(f'{tag}-card', look['card']), card_edge=flat(f'{tag}-card-edge', look['card_edge']), card_text=flat(f'{tag}-card-text', look['card_text']))
        M['line'].use_backface_culling = True
        _BUDDY_MATS[key] = M
    return _BUDDY_MATS[key]


def buddy(location, facing=0.0, name='buddy', card=None, arm=0.0, lean=0.0, gaze=(0.045, 0.0), look=None, register=True):
    """Buddy in 3D — the ready-made narrator of lib/buddy.js as a solid: a gumdrop body with an outline, big eyes, cheeks, thin
    limbs and shoes. About 2.6 tall (give it your own headgear by parenting a mesh to the returned `up`).
    location: where its feet stand · facing: degrees about the vertical (0 looks down -Y, toward a camera that looks along +Y;
    positive turns it toward +X, to the right of the frame) · card: a few Latin letters or digits on a card in its raised right
    hand (Blender's built-in font has nothing else), or None · arm: degrees the right arm drops from the raised pose (0 raised,
    58 down) · lean: degrees the body tips forward · gaze: (x, z) shift of the pupils ·
    look: colours that differ from BUDDY_LOOK — body, outline, limb, shoe, blush, eye, pupil, mouth, rim (a third tone on the
    edge of the body that catches the sun, or None), card, card_edge, card_text. Each lit part gets two flat tones made from its colour.
    Returns {root, up, arm, shoulder, hand}: `up` is the body (squash it, tip it), `arm` the pivot the right arm and whatever it
    holds hang from — parent your own prop to `arm` and it is rendered with the arm.
    With register=True the body becomes actor `name` and the arm actor `name-arm` (pivot at the shoulder), and the anchor
    `name-feet` is set. For a second pose, build a second one under another name at the same place: each is its own layer."""
    M = _buddy_mats({**BUDDY_LOOK, **(look or {})}); n = name
    root = add(bpy.data.objects.new(n, None)); root.location = location; root.rotation_euler = (0, 0, math.radians(facing))
    up = add(bpy.data.objects.new(f'{n}-upper', None)); up.parent = root; up.location = (0, 0, 0.2); up.rotation_euler = (math.radians(lean), 0, 0)
    body = lathe(f'{n}-body', [(0.0, 0.42), (0.34, 0.42), (0.56, 0.46), (0.69, 0.58), (0.745, 0.85), (0.75, 1.45), (0.71, 1.82), (0.6, 2.1), (0.42, 2.28), (0.2, 2.36), (0.0, 2.38)], M['body'], sy=0.84)
    body.data.materials.append(M['line']); body.parent = up
    sol = body.modifiers.new('outline', 'SOLIDIFY'); sol.thickness = 0.05; sol.offset = 1.0; sol.use_flip_normals = True; sol.material_offset = 1; sol.use_rim = False
    sub = body.modifiers.new('smooth', 'SUBSURF'); sub.levels = 1; sub.render_levels = 1

    def on_face(x, z, lift=0.0):
        """a point on the front of the body (the face looks down -Y), pushed out by `lift`"""
        r = 0.745 if 0.85 <= z <= 1.45 else (0.71 - (z - 1.82) * 0.4 if z > 1.45 else 0.72)
        r = max(0.3, min(0.75, r))
        return (x, -0.84 * math.sqrt(max(0.01, r * r - x * x)) - lift, z)

    for sx in (-1, 1):
        ex = 0.27 * sx + 0.03
        ball(f'{n}-eye{sx}', on_face(ex, 1.76, 0.0), (0.175, 0.07, 0.205), M['eye'], up)
        ball(f'{n}-pupil{sx}', on_face(ex + gaze[0], 1.755 + gaze[1], 0.055), (0.095, 0.035, 0.115), M['pupil'], up)
        ball(f'{n}-glint{sx}', on_face(ex + gaze[0] + 0.04, 1.82 + gaze[1], 0.085), (0.032, 0.015, 0.032), M['eye'], up)
        ball(f'{n}-blush{sx}', on_face(0.5 * sx + 0.03, 1.47, -0.01), (0.12, 0.04, 0.075), M['blush'], up, rot=(0, 0, math.radians(38 * sx)))
        tube(f'{n}-leg{sx}', [(0.23 * sx, 0.0, 0.72), (0.23 * sx, 0.0, 0.4), (0.23 * sx, -0.02, 0.1)], [0.062, 0.062, 0.062], M['limb'], res=4, parent=root)
        ball(f'{n}-shoe{sx}', (0.23 * sx, -0.09, 0.1), (0.175, 0.27, 0.105), M['shoe'], root)
    ball(f'{n}-mouth', on_face(0.05, 1.5, 0.0), (0.058, 0.03, 0.078), M['mouth'], up)
    tube(f'{n}-arm_l', [(-0.68, -0.02, 1.3), (-0.84, -0.03, 1.08), (-0.86, -0.06, 0.86)], [0.058, 0.055, 0.052], M['limb'], res=6, parent=up)
    ball(f'{n}-hand_l', (-0.86, -0.06, 0.84), (0.095, 0.095, 0.095), M['limb'], up)
    # the right arm hangs from a pivot at the shoulder, with whatever it holds
    shoulder = Vector((0.66, -0.12, 1.32))
    pivot = add(bpy.data.objects.new(f'{n}-arm', None)); pivot.parent = up; pivot.location = shoulder; pivot.rotation_euler = (0, math.radians(arm), 0)
    held = [tube(f'{n}-arm_r', [(0.66, -0.12, 1.32), (0.98, -0.3, 1.34), (1.24, -0.42, 1.5)], [0.058, 0.055, 0.052], M['limb'], res=6),
            ball(f'{n}-hand_r', (1.26, -0.43, 1.52), (0.095, 0.095, 0.095), M['limb'])]
    if card:
        tilt = (math.radians(-6), math.radians(-8), math.radians(-6))
        held.append(quad(f'{n}-card_edge', 1.1, 0.74, M['card_edge'], (1.62, -0.5, 1.86), tilt))
        held.append(quad(f'{n}-card', 1.0, 0.64, M['card'], (1.62, -0.515, 1.86), tilt))
        fc = bpy.data.curves.new(f'{n}-card_text', 'FONT'); fc.body = card; fc.align_x = 'CENTER'; fc.align_y = 'CENTER'; fc.size = 0.36
        fc.materials.append(M['card_text']); tx = add(bpy.data.objects.new(f'{n}-card_text', fc))
        tx.location = (1.62, -0.53, 1.84); tx.rotation_euler = (math.radians(90) + tilt[0], tilt[1], tilt[2]); held.append(tx)
    for o in held:
        o.parent = pivot; o.location = Vector(o.location) - shoulder
    if register:
        actor(n, root, exclude=(pivot,)); actor(f'{n}-arm', pivot, pivot=pivot); anchor(f'{n}-feet', root)
    return {'root': root, 'up': up, 'arm': pivot, 'shoulder': shoulder, 'hand': Vector((1.26, -0.43, 1.52)) - shoulder}


# ───────────────────────── a painterly pass (compositor) ─────────────────────────
def _post(edge_far=400.0):
    vl = bpy.context.view_layer; vl.use_pass_z = True
    ng = bpy.data.node_groups.new('post', 'CompositorNodeTree')
    ng.interface.new_socket('Image', in_out='OUTPUT', socket_type='NodeSocketColor')
    rl = ng.nodes.new('CompositorNodeRLayers'); go = ng.nodes.new('NodeGroupOutput')

    def setin(node, name, value):
        for i in node.inputs:
            if i.name == name:
                try:
                    i.default_value = value
                    return True
                except Exception as e:
                    print('setin', node.bl_idname, name, repr(e))
        return False

    def cmath(op, a, b=None):
        n = ng.nodes.new('ShaderNodeMath'); n.operation = op
        for i, v in enumerate((a, b)):
            if v is None:
                continue
            if isinstance(v, (int, float)):
                n.inputs[i].default_value = v
            else:
                ng.links.new(v, n.inputs[i])
        return n.outputs[0]

    def blur(sock, px):
        bl = ng.nodes.new('CompositorNodeBlur'); setin(bl, 'Size', (px * RS, px * RS))
        ng.links.new(sock, next(i for i in bl.inputs if i.name == 'Image'))
        return bl.outputs[0]

    def crange(v, a, b, c, d):
        mr = ng.nodes.new('ShaderNodeMapRange'); mr.clamp = True; ng.links.new(v, mr.inputs[0])
        for i, x in zip((1, 2, 3, 4), (a, b, c, d)):
            mr.inputs[i].default_value = x
        return mr.outputs[0]

    img = rl.outputs[0]
    if KUW > 0:
        ku = ng.nodes.new('CompositorNodeKuwahara'); setin(ku, 'Size', KUW * RS); setin(ku, 'Type', 'Anisotropic'); setin(ku, 'Sharpness', 0.6)
        ng.links.new(img, ku.inputs[0]); img = ku.outputs[0]
    if EDGE > 0:
        try:
            depth = next(o for o in rl.outputs if o.name in ('Depth', 'Z'))
            lg = cmath('LOGARITHM', cmath('MINIMUM', depth, edge_far), math.e)      # past edge_far nothing gets an outline (the sun, the last range)
            fi = ng.nodes.new('CompositorNodeFilter')
            if not setin(fi, 'Type', 'Sobel'):
                fi.filter_type = 'SOBEL'
            ng.links.new(lg, next(i for i in fi.inputs if i.name == 'Image'))
            e = crange(fi.outputs[0], 0.2, 1.2, 0.0, 1.0)
            line = cmath('MAXIMUM', cmath('MULTIPLY', blur(e, 1.0), 1.0), cmath('MULTIPLY', blur(e, 4.5), 0.36))   # the stroke, and the wash that bleeds off it
            # where the picture is already blank paper (mist, sky), draw nothing. A slab rendered on its own is transparent
            # there (black, which would read as "dark: draw"), so it is judged as it will look laid over paper.
            try:
                seen = ng.nodes.new('ShaderNodeMix'); seen.data_type = 'RGBA'
                ng.links.new(next(o for o in rl.outputs if o.name == 'Alpha'), seen.inputs[0]); seen.inputs[6].default_value = lin(PAPER); ng.links.new(img, seen.inputs[7])
                dark = crange(seen.outputs[2], 0.5, 0.74, 1.0, 0.0)             # pale things (far ranges, anything under mist) get little or no contour
            except StopIteration:
                dark = crange(img, 0.62, 0.8, 1.0, 0.0)
            fac = cmath('MULTIPLY', cmath('MULTIPLY', line, dark), EDGE)
            STATE['edge'] = fac.node.inputs[1]                                   # a flight may thin the contour while it is fast: STATE['edge'].default_value = …
            mx = ng.nodes.new('ShaderNodeMix'); mx.data_type = 'RGBA'
            ng.links.new(fac, mx.inputs[0]); ng.links.new(img, mx.inputs[6]); mx.inputs[7].default_value = lin(INK)
            img = mx.outputs[2]
        except Exception as e:
            print('EDGE failed:', repr(e))
    ng.links.new(img, go.inputs[0])
    scene.compositing_node_group = ng; scene.render.use_compositing = True


# ───────────────────────── a flight (the only place frames are rendered one by one) ─────────────────────────
def fly(pose, seconds, fps=30, shutter=0.5, each=None, edge_far=400.0):
    """Render a camera move as frames <OUT>0001.jpg …: pose(t) → (location, aim, roll in degrees) at t seconds. The camera is
    baked to keyframes (so motion blur sees it move inside a frame). each(t), if given, runs before every frame.
    keys: from=<first frame, 1-based>  to=<last>  step=<every n-th>  shutter=0.5 (0 = no motion blur)  jpg=90"""
    from mathutils import Quaternion
    co = STATE['camobj']; co.rotation_mode = 'QUATERNION'; n = int(round(seconds * fps)); prev = None
    for f in range(n + 1):
        loc, aim, roll = pose(f / fps)
        q = (Vector(aim) - Vector(loc)).to_track_quat('-Z', 'Y')
        if roll:
            q = q @ Quaternion((0.0, 0.0, 1.0), math.radians(roll))
        if prev is not None:
            q.make_compatible(prev)
        co.location = loc; co.rotation_quaternion = q; prev = q.copy()
        co.keyframe_insert('location', frame=f + 1); co.keyframe_insert('rotation_quaternion', frame=f + 1)
    if each:
        bpy.app.handlers.frame_change_pre.append(lambda sc, *_: each((sc.frame_current - 1) / fps))
    sh = float(OPT.get('shutter', shutter))
    scene.render.use_motion_blur = sh > 0; scene.render.motion_blur_shutter = sh
    scene.frame_start = int(OPT.get('from', 1)); scene.frame_end = int(OPT.get('to', n + 1)); scene.frame_step = int(OPT.get('step', 1)); scene.render.fps = fps
    scene.render.image_settings.file_format = 'JPEG'; scene.render.image_settings.quality = int(OPT.get('jpg', 90)); scene.render.image_settings.color_mode = 'RGB'
    if POST:
        _post(edge_far)
    scene.render.filepath = OUT
    import time
    t0 = time.time(); bpy.ops.render.render(animation=True)
    count = len(range(scene.frame_start, scene.frame_end + 1, scene.frame_step))
    print(f'FLIGHT {count} frames in {time.time() - t0:.1f} s = {(time.time() - t0) / max(1, count):.2f} s/frame')


# ───────────────────────── render ─────────────────────────
def _frame_px(point):
    """a world point (or an object's origin) → (x, y) in the 1920×1080 frame (origin top-left; may fall outside) and its distance in front of the camera"""
    ox, oy = STATE['over']; co = STATE['camobj']
    v = world_to_camera_view(scene, co, point.matrix_world.translation if isinstance(point, bpy.types.Object) else Vector(point))
    return (v.x - 0.5) * FRAME_W * ox + FRAME_W / 2, (0.5 - v.y) * FRAME_H * oy + FRAME_H / 2, v.z


def finish(slabs=None, edge_far=400.0):
    """Render. slabs = [(name, near, far), …] or (name, near, far, depth): the ranges of distance from the camera the picture is
    cut into, nearest first (mode=layers). A solid goes to the slab that holds the middle of its bounding box; span() and mist
    go to all of them. `depth` (how far the page treats the slab as being, which sets how much it slides) defaults to the mean
    distance of what the slab holds. Cut between things, never through a hill or a bank of cloud: the halves slide apart."""
    cam, co = STATE['cam'], STATE['camobj']
    if POST:
        _post(edge_far)
    bpy.context.view_layer.update()
    if MODE != 'layers':
        scene.render.filepath = OUT; bpy.ops.render.render(write_still=True)
        print('RENDERED', OUT)
        return
    ox, oy = STATE['over']
    scene.render.film_transparent = True; scene.render.image_settings.color_mode = 'RGBA'
    view = co.matrix_world.inverted()
    mid = lambda o: -(view @ (o.matrix_world @ Vector(o.bound_box[0]).lerp(Vector(o.bound_box[6]), 0.5))).z   # the middle of its box, not its origin

    def family(root, exclude=()):
        skip = set()
        for e in exclude:
            skip |= {e} | set(e.children_recursive)
        return {o for o in [root] + list(root.children_recursive) if o not in skip}

    cast = [(name, family(root, ex), root, pivot) for name, root, ex, pivot in ACTORS]
    who = set().union(*[f for _, f, _, _ in cast]) if cast else set()
    banks = set(CLOUDS); mists = set(MISTS)
    rest = [o for o in col.objects if o not in who and o not in banks and o not in mists and o.type in ('MESH', 'CURVE', 'FONT')]

    def show(group):
        for o in col.objects:
            o.hide_render = o not in group and o.type != 'LIGHT'     # the sun shines on every slab, as it does in a still

    eye = co.matrix_world.translation; ahead = co.matrix_world.to_quaternion() @ Vector((0.0, 0.0, -1.0))
    for _, _, cp, cd in SLAB_NODES:
        for i in range(3):
            cp.inputs[i].default_value = eye[i]; cd.inputs[i].default_value = ahead[i]
    out = []
    for slab in slabs or [('all', 0.1, 3000.0)]:
        name, a0, b0 = slab[:3]
        cam.clip_start, cam.clip_end = a0, b0; ee.volumetric_start, ee.volumetric_end = max(0.5, a0), min(700.0, b0)   # for volumes a scene made itself
        for near, far, _, _ in SLAB_NODES:                 # the kit's own mist and cloud: this slab's part only (see _in_slab)
            near.outputs[0].default_value = a0 if a0 > 0.2 else -1e9; far.outputs[0].default_value = b0
        inside = lambda o: a0 <= mid(o) < b0
        solids = [o for o in rest if o not in SPAN and inside(o)]
        # the banks of cloud are rendered WITH the solids of the slab (every bank in every slab: the volume range keeps the part
        # that lies in this one), so what hides what inside a slab is decided by the renderer, as in a still. On layers of their
        # own (clouds=1) they can drift, but they are then stacked wholly in front of the slab's hills and wash them out.
        split = OPT.get('clouds', '0') == '1'
        show(set(solids) | SPAN | mists | (set() if split else banks)); scene.render.use_compositing = POST
        scene.render.filepath = f'{OUT}{name}.png'; bpy.ops.render.render(write_still=True)
        zs = [mid(o) for o in solids]
        d = slab[3] if len(slab) > 3 else (sum(zs) / len(zs) if zs else (a0 + b0) / 2)
        out.append({'id': name, 'file': f'{name}.png', 'depth': round(d, 1), 'kind': 'ground'})
        mine = [c for c in CLOUDS if inside(c)] if split else []
        if mine:
            show(set(mine)); scene.render.filepath = f'{OUT}{name}-cloud.png'; bpy.ops.render.render(write_still=True)
            out.append({'id': f'{name}-cloud', 'file': f'{name}-cloud.png', 'depth': round(sum(mid(c) for c in mine) / len(mine), 1), 'kind': 'cloud'})
        print('SLAB', name, a0, b0, 'solids', len(solids), 'clouds', len(mine), 'depth', round(d, 1))
    cam.clip_start, cam.clip_end = 0.1, 3000.0; scene.render.use_compositing = False      # actors stay crisp: no painterly pass
    for name, fam, root, pivot in cast:
        show(fam); scene.render.filepath = f'{OUT}{name}.png'; bpy.ops.render.render(write_still=True)
        entry = {'id': name, 'file': f'{name}.png', 'depth': round(-(view @ root.matrix_world.translation).z, 1), 'kind': 'actor'}
        if pivot is not None:
            x, y, _ = _frame_px(pivot); entry['pivot'] = [round(x, 1), round(y, 1)]
        out.append(entry)
    anchors = {}
    for k, (p, size) in ANCHORS.items():
        x, y, z = _frame_px(p); anchors[k] = {'x': round(x, 1), 'y': round(y, 1), 'depth': round(z, 1)}
        if size:
            anchors[k]['r'] = round(size * FOCAL_PX / z, 1)
    meta = {'width': FRAME_W, 'height': FRAME_H, 'px': RS, 'over': [ox, oy], 'focal': round(FOCAL_PX, 1), 'layers': out, 'anchors': anchors}
    json.dump(meta, open(f'{OUT}layers.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('LAYERS', len(out), 'ANCHORS', len(anchors))
