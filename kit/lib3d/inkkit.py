def lin(hexstr):
    """#RRGGBB (sRGB) → linear RGBA"""
    h = hexstr.lstrip('#')
    def f(c):
        c = int(c, 16) / 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    return (f(h[0:2]), f(h[2:4]), f(h[4:6]), 1.0)


