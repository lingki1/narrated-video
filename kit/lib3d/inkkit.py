def new_mat(name):
    m = bpy.data.materials.new(name); m.use_nodes = True; m.node_tree.nodes.clear()
    return m, m.node_tree


def fnode(nt, op, a, b=None, clamp=False):
    n = nt.nodes.new('ShaderNodeMath'); n.operation = op; n.use_clamp = clamp
    for i, v in enumerate((a, b)):
        if v is None:
            continue
        if isinstance(v, (int, float)):
            n.inputs[i].default_value = v
        else:
            nt.links.new(v, n.inputs[i])
    return n.outputs[0]


def map_range(nt, v, a, b, c, d, smooth=True):
    n = nt.nodes.new('ShaderNodeMapRange'); n.clamp = True
    if smooth:
        n.interpolation_type = 'SMOOTHSTEP'
    nt.links.new(v, n.inputs[0])
    for i, x in zip((1, 2, 3, 4), (a, b, c, d)):
        if isinstance(x, (int, float)):
            n.inputs[i].default_value = x
        else:
            nt.links.new(x, n.inputs[i])
    return n.outputs[0]


def mix_rgb(nt, fac, a, b):
    n = nt.nodes.new('ShaderNodeMix'); n.data_type = 'RGBA'
    for sock, v in ((n.inputs[0], fac), (n.inputs[6], a), (n.inputs[7], b)):
        if isinstance(v, (int, float, tuple)):
            sock.default_value = v
        else:
            nt.links.new(v, sock)
    return n.outputs[2]


def noise_at(nt, pos, scale, size, detail=6.0):
    mp = nt.nodes.new('ShaderNodeMapping'); mp.inputs[3].default_value = scale; nt.links.new(pos, mp.inputs[0])
    nz = nt.nodes.new('ShaderNodeTexNoise'); nz.inputs[2].default_value = size; nz.inputs[3].default_value = detail
    nt.links.new(mp.outputs[0], nz.inputs[0])
    return nz.outputs[0]


def emit(nt, color_socket):
    e = nt.nodes.new('ShaderNodeEmission'); nt.links.new(color_socket, e.inputs[0]); e.inputs[1].default_value = 1.0
    nt.links.new(e.outputs[0], nt.nodes.new('ShaderNodeOutputMaterial').inputs[0])


def flat(name, hexstr):
    """one flat colour, no light on it"""
    m, nt = new_mat(name)
    rgb = nt.nodes.new('ShaderNodeRGB'); rgb.outputs[0].default_value = lin(hexstr)
    emit(nt, rgb.outputs[0])
    return m


def lit(nt):
    d = nt.nodes.new('ShaderNodeBsdfDiffuse'); d.inputs[0].default_value = (1, 1, 1, 1)
    s = nt.nodes.new('ShaderNodeShaderToRGB'); nt.links.new(d.outputs[0], s.inputs[0])
    return s.outputs[0]


def toon(name, dark, light, at=0.42, rim=None):
    """two flat tones (away from the sun / toward it); rim = a third tone on the edge that catches the sun"""
    m, nt = new_mat(name); L = lit(nt)
    r = nt.nodes.new('ShaderNodeValToRGB'); r.color_ramp.interpolation = 'CONSTANT'
    r.color_ramp.elements[0].position = 0.0; r.color_ramp.elements[0].color = lin(dark)
    r.color_ramp.elements[1].position = at; r.color_ramp.elements[1].color = lin(light)
    nt.links.new(L, r.inputs[0]); out = r.outputs[0]
    if rim:
        lw = nt.nodes.new('ShaderNodeLayerWeight'); lw.inputs[0].default_value = 0.5
        edge = map_range(nt, lw.outputs[1], 0.78, 0.82, 0.0, 1.0, smooth=False)
        out = mix_rgb(nt, fnode(nt, 'MULTIPLY', edge, map_range(nt, L, at, at + 0.02, 0.0, 1.0, smooth=False)), out, lin(rim))
    emit(nt, out)
    return m


INK_STOPS = [(0.0, PAPER), (0.16, '#D3CFC8'), (0.36, '#96938F'), (0.56, '#57555A'), (0.78, '#242327'), (1.0, INK)]


def ink(name, base=0.08, shade=0.45, crevice=0.4, top=0.25, edge=0.25, streak=0.22, blot=0.12, streak_scale=(0.16, 0.16, 0.035), blot_scale=0.02,
        ao=4.0, far=(40.0, 260.0), far_k=0.4, mist=None, crack=None, stops=None, wash=None, wash_scale=0.03):
    """how much ink (0 paper … 1 full) lands on a point of a surface, then the ramp that turns it into a wash.
    base: ink everywhere · shade: more on the side away from the sun · crevice: more in corners (ao = how wide a corner counts) ·
    top: more toward the top of the object · edge: more where the surface turns away from the eye · streak / blot: noise, stretched
    (streak_scale) and round (blot_scale) · far=(a, b), far_k: thinned to far_k between a and b units from the camera ·
    mist=(z0, z1): no ink below z0, full above z1 (only when there is no fog volume) · crack=(scale, width, amount): joints in rock ·
    wash=[(colour, amount, where), …]: thin colour laid over the ink, as in a painted landscape (the ink still shows through:
    the colour multiplies it). where: 'top' toward the top of the object · 'low' toward its foot · 'sun' the lit side ·
    'shade' the other side · 'all'. It pools unevenly (wash_scale = the size of the pooling noise). Colours: AZURITE, MALACHITE,
    OCHRE, INDIGO, GAMBOGE, ROUGE or any hex; amount 0.3–0.9. Far things keep their colour while their ink thins: blue-green distance."""
    m, nt = new_mat(name); L = lit(nt)
    geo = nt.nodes.new('ShaderNodeNewGeometry'); pos = geo.outputs[0]
    v = fnode(nt, 'ADD', base, fnode(nt, 'MULTIPLY', fnode(nt, 'SUBTRACT', 1.0, L, clamp=True), shade))
    if crevice:
        a = nt.nodes.new('ShaderNodeAmbientOcclusion'); a.inputs[1].default_value = ao
        try:
            a.samples = 16
        except Exception:
            pass
        v = fnode(nt, 'ADD', v, fnode(nt, 'MULTIPLY', map_range(nt, a.outputs[1], 0.25, 0.95, 1.0, 0.0), crevice))
    if top:
        tc = nt.nodes.new('ShaderNodeTexCoord'); gz = nt.nodes.new('ShaderNodeSeparateXYZ'); nt.links.new(tc.outputs[0], gz.inputs[0])
        v = fnode(nt, 'ADD', v, fnode(nt, 'MULTIPLY', map_range(nt, gz.outputs[2], 0.3, 1.0, 0.0, 1.0), top))
    if edge:
        lw = nt.nodes.new('ShaderNodeLayerWeight'); lw.inputs[0].default_value = 0.5
        v = fnode(nt, 'ADD', v, fnode(nt, 'MULTIPLY', map_range(nt, lw.outputs[1], 0.5, 0.97, 0.0, 1.0), edge))
    if streak:
        v = fnode(nt, 'ADD', v, fnode(nt, 'MULTIPLY', map_range(nt, noise_at(nt, pos, streak_scale, 5.0), 0.3, 0.7, -1.0, 1.0, smooth=False), streak))
    if blot:
        v = fnode(nt, 'ADD', v, fnode(nt, 'MULTIPLY', map_range(nt, noise_at(nt, pos, (blot_scale,) * 3, 3.0, 2.0), 0.3, 0.7, -1.0, 1.0, smooth=False), blot))
    if crack:   # (scale, width, amount): the joints between the cells of a stretched Voronoi pattern
        mp = nt.nodes.new('ShaderNodeMapping'); mp.inputs[3].default_value = crack[0]; nt.links.new(pos, mp.inputs[0])
        vo = nt.nodes.new('ShaderNodeTexVoronoi'); vo.feature = 'DISTANCE_TO_EDGE'; nt.links.new(mp.outputs[0], vo.inputs[0])
        for i in vo.inputs:
            if i.name == 'Scale':
                i.default_value = 1.0
        v = fnode(nt, 'ADD', v, fnode(nt, 'MULTIPLY', map_range(nt, vo.outputs[0], 0.0, crack[1], 1.0, 0.0), crack[2]))
    if mist:
        sep = nt.nodes.new('ShaderNodeSeparateXYZ'); nt.links.new(pos, sep.inputs[0])
        v = fnode(nt, 'MULTIPLY', v, map_range(nt, sep.outputs[2], mist[0], mist[1], 0.0, 1.0))
    cam = nt.nodes.new('ShaderNodeCameraData')
    v = fnode(nt, 'MULTIPLY', v, map_range(nt, cam.outputs[1], far[0], far[1], 1.0, far_k), clamp=True)
    r = nt.nodes.new('ShaderNodeValToRGB'); r.color_ramp.interpolation = 'EASE'
    st = stops or INK_STOPS
    r.color_ramp.elements[0].position = st[0][0]; r.color_ramp.elements[0].color = lin(st[0][1])
    r.color_ramp.elements[1].position = st[-1][0]; r.color_ramp.elements[1].color = lin(st[-1][1])
    for p, c in st[1:-1]:
        r.color_ramp.elements.new(p).color = lin(c)
    nt.links.new(v, r.inputs[0]); out = r.outputs[0]
    if wash:
        tc = nt.nodes.new('ShaderNodeTexCoord'); gz = nt.nodes.new('ShaderNodeSeparateXYZ'); nt.links.new(tc.outputs[0], gz.inputs[0]); hz = gz.outputs[2]
        pool = map_range(nt, noise_at(nt, pos, (wash_scale,) * 3, 2.0, 3.0), 0.3, 0.7, 0.45, 1.0)
        for colour, amount, where in wash:
            k = {'top': lambda: map_range(nt, hz, 0.3, 0.9, 0.0, 1.0), 'low': lambda: map_range(nt, hz, 0.05, 0.55, 1.0, 0.0),
                 'sun': lambda: map_range(nt, L, 0.25, 0.8, 0.0, 1.0), 'shade': lambda: map_range(nt, L, 0.25, 0.8, 1.0, 0.0), 'all': lambda: None}[where]()
            fac = fnode(nt, 'MULTIPLY', pool, amount) if k is None else fnode(nt, 'MULTIPLY', fnode(nt, 'MULTIPLY', k, pool), amount)
            mx = nt.nodes.new('ShaderNodeMix'); mx.data_type = 'RGBA'; mx.blend_type = 'MULTIPLY'
            nt.links.new(fac, mx.inputs[0]); nt.links.new(out, mx.inputs[6]); mx.inputs[7].default_value = lin(colour); out = mx.outputs[2]
    emit(nt, out)
    return m


SLAB_NODES = []   # per volume material: (near, far, camera position, camera forward) — finish() sets them slab by slab


def _in_slab(nt, pos):
    """1 where a point of a volume lies in the slab being rendered (by its distance in front of the camera), else 0. In a still it is 1
    everywhere. Cutting the volume here, instead of narrowing the renderer's volume range, keeps the mist sampled exactly as in
    a still, so the slabs stacked back up give the still's mist and not a denser one."""
    near = nt.nodes.new('ShaderNodeValue'); near.outputs[0].default_value = -1e9; far = nt.nodes.new('ShaderNodeValue'); far.outputs[0].default_value = 1e9
    cp = nt.nodes.new('ShaderNodeCombineXYZ'); cd = nt.nodes.new('ShaderNodeCombineXYZ'); cd.inputs[1].default_value = 1.0
    rel = nt.nodes.new('ShaderNodeVectorMath'); rel.operation = 'SUBTRACT'; nt.links.new(pos, rel.inputs[0]); nt.links.new(cp.outputs[0], rel.inputs[1])
    dot = nt.nodes.new('ShaderNodeVectorMath'); dot.operation = 'DOT_PRODUCT'; nt.links.new(rel.outputs[0], dot.inputs[0]); nt.links.new(cd.outputs[0], dot.inputs[1])
    z = dot.outputs['Value']; SLAB_NODES.append((near, far, cp, cd))
    return fnode(nt, 'MULTIPLY', fnode(nt, 'GREATER_THAN', z, near.outputs[0]), fnode(nt, 'LESS_THAN', z, far.outputs[0]))


def fog_material(top=0.6, swell=2.0, depth=2.0, density=0.4, name='mist'):
    """mist with a billowing top at height `top`; it absorbs what is behind it and glows by exactly as much, so thick mist is exactly paper"""
    m, nt = new_mat(name)
    geo = nt.nodes.new('ShaderNodeNewGeometry'); pos = geo.outputs[0]
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); nt.links.new(pos, sep.inputs[0]); z = sep.outputs[2]
    big = map_range(nt, noise_at(nt, pos, (0.011, 0.016, 0.0), 1.0, 3.0), 0.25, 0.75, -1.0, 1.0, smooth=False)
    small = map_range(nt, noise_at(nt, pos, (0.05, 0.07, 0.0), 1.0, 2.0), 0.25, 0.75, -1.0, 1.0, smooth=False)
    surf = fnode(nt, 'ADD', top, fnode(nt, 'ADD', fnode(nt, 'MULTIPLY', big, swell), fnode(nt, 'MULTIPLY', small, swell * 0.3)))
    under = fnode(nt, 'SUBTRACT', surf, z)
    d = fnode(nt, 'MULTIPLY', fnode(nt, 'MULTIPLY', map_range(nt, under, 0.0, depth, 0.0, 1.0), density), _in_slab(nt, pos))
    tone = mix_rgb(nt, map_range(nt, under, 0.3, 5.0, 1.0, 0.0), lin('#D5D0C9'), lin(PAPER))
    ab = nt.nodes.new('ShaderNodeVolumeAbsorption'); ab.inputs[0].default_value = (0, 0, 0, 1); nt.links.new(d, ab.inputs[1])
    em = nt.nodes.new('ShaderNodeEmission'); nt.links.new(tone, em.inputs[0]); nt.links.new(d, em.inputs[1])
    ad = nt.nodes.new('ShaderNodeAddShader'); nt.links.new(ab.outputs[0], ad.inputs[0]); nt.links.new(em.outputs[0], ad.inputs[1])
    nt.links.new(ad.outputs[0], nt.nodes.new('ShaderNodeOutputMaterial').inputs[1])
    return m


def cloud_material(density=0.22, name='cloud'):
    """a bank of cloud: thick in the middle of its ellipsoid, wispy toward the edge, paper on top and a breath of grey underneath"""
    m, nt = new_mat(name)
    tc = nt.nodes.new('ShaderNodeTexCoord'); obj = tc.outputs[3]
    ln = nt.nodes.new('ShaderNodeVectorMath'); ln.operation = 'LENGTH'; nt.links.new(obj, ln.inputs[0])
    geo = nt.nodes.new('ShaderNodeNewGeometry')
    wisp = map_range(nt, noise_at(nt, geo.outputs[0], (0.07, 0.09, 0.3), 1.0, 4.0), 0.36, 0.62, 0.0, 1.0)
    d = fnode(nt, 'MULTIPLY', fnode(nt, 'MULTIPLY', fnode(nt, 'MULTIPLY', map_range(nt, ln.outputs[1], 1.0, 0.3, 0.0, 1.0), wisp), density), _in_slab(nt, geo.outputs[0]))
    sep = nt.nodes.new('ShaderNodeSeparateXYZ'); nt.links.new(obj, sep.inputs[0])
    tone = mix_rgb(nt, map_range(nt, sep.outputs[2], -0.6, 0.25, 0.0, 1.0), lin('#C9C4BC'), lin(PAPER))
    ab = nt.nodes.new('ShaderNodeVolumeAbsorption'); ab.inputs[0].default_value = (0, 0, 0, 1); nt.links.new(d, ab.inputs[1])
    em = nt.nodes.new('ShaderNodeEmission'); nt.links.new(tone, em.inputs[0]); nt.links.new(d, em.inputs[1])
    ad = nt.nodes.new('ShaderNodeAddShader'); nt.links.new(ab.outputs[0], ad.inputs[0]); nt.links.new(em.outputs[0], ad.inputs[1])
    nt.links.new(ad.outputs[0], nt.nodes.new('ShaderNodeOutputMaterial').inputs[1])
    return m


# ───────────────────────── meshes ─────────────────────────
def smooth(me):
    try:
        me.shade_smooth()
    except Exception:
        me.polygons.foreach_set('use_smooth', [True] * len(me.polygons))


def mesh(name, verts, faces, mat, smooth_shade=False, parent=None):
    """any mesh from points and faces (faces list their corners counter-clockwise seen from outside)"""
    me = bpy.data.meshes.new(name); me.from_pydata(verts, [], faces); me.update()
    if smooth_shade:
        smooth(me)
    if mat:
        me.materials.append(mat)
    o = add(bpy.data.objects.new(name, me))
    if parent:
        o.parent = parent
    return o


def box(name, center, size, mat, rot_z=0.0, parent=None):
    """a block: centre (x, y, z), size (along x, along y, along z), turned rot_z degrees about the vertical"""
    hx, hy, hz = size[0] / 2, size[1] / 2, size[2] / 2
    v = [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, hy, -hz), (-hx, hy, -hz), (-hx, -hy, hz), (hx, -hy, hz), (hx, hy, hz), (-hx, hy, hz)]
    f = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    o = mesh(name, v, f, mat, parent=parent); o.location = center; o.rotation_euler = (0, 0, math.radians(rot_z))
    return o


def grid_mesh(name, x0, x1, y0, y1, nx, ny, height, mat, floor=None):
    """a sheet over [x0, x1] × [y0, y1] whose height is height(x, y); faces that lie on `floor` are left out"""
    verts = []; faces = []
    for j in range(ny + 1):
        y = y0 + (y1 - y0) * j / ny
        for i in range(nx + 1):
            x = x0 + (x1 - x0) * i / nx
            verts.append((x, y, height(x, y)))
    for j in range(ny):
        for i in range(nx):
            a = j * (nx + 1) + i; f = (a, a + 1, a + nx + 2, a + nx + 1)
            if floor is None or any(verts[k][2] > floor + 1e-4 for k in f):
                faces.append(f)
    me = bpy.data.meshes.new(name); me.from_pydata(verts, [], faces); me.update(); smooth(me); me.materials.append(mat)
    return add(bpy.data.objects.new(name, me))


def strata(z, band, k=0.8):
    """bands of cliff and ledge: steep, flat, steep, flat (stays monotonic for k < 1)"""
    return z - k * band / math.tau * math.sin(math.tau * z / band)


def peaks_height(peaks, base, seed, crag=0.36, pw=1.15, flutes=7, band=0.16):
    """height(x, y) of a massif: peaks = [(x, y, height, radius), …] standing on `base`; crag = how rough, pw = how pointed
    (below 1: spires), flutes = buttresses and gullies running from each summit, band = ledges as a share of the height"""
    def h(x, y):
        z = 0.0
        for k, (px, py, hh, r) in enumerate(peaks):
            dx, dy = x - px, y - py; th = math.atan2(dy, dx)
            fl = 0.5 + 0.5 * math.sin(th * flutes + 4.0 * noise.noise(Vector((math.cos(th) * 1.3 + seed + k, math.sin(th) * 1.3, 0.0))))
            d = math.hypot(dx, dy) / (r * (0.7 + 0.36 * fl))
            if d < 1:
                z = max(z, hh * (1 - d) ** pw)
        if z > 0:
            hh0, r0 = peaks[0][2], peaks[0][3]
            rid = noise.ridged_multi_fractal(Vector((x / r0 * 2.4 + seed, y / r0 * 2.4, seed * 0.37)), 1.0, 2.1, 5, 1.0, 2.0)
            fine = noise.fractal(Vector((x / r0 * 9 + seed, y / r0 * 9, 1.7)), 1.0, 2.0, 4)
            z *= (1 - crag) + crag * min(2.0, rid) * 0.8 + 0.05 * fine
            z = strata(z, hh0 * band)
        return base + z
    return h


def mountain(name, peaks, base, seed, mat, n=150, **kw):
    x0 = min(p[0] - p[3] for p in peaks); x1 = max(p[0] + p[3] for p in peaks)
    y0 = min(p[1] - p[3] for p in peaks); y1 = max(p[1] + p[3] for p in peaks)
    return grid_mesh(name, x0, x1, y0, y1, n, max(40, int(n * (y1 - y0) / (x1 - x0))), peaks_height(peaks, base, seed, **kw), mat, floor=base)


def tube(name, pts, radii, mat, res=10, parent=None):
    """a rounded stroke through points, as thick as `radii` at each (trunks, boughs, limbs, ropes, poles)"""
    cu = bpy.data.curves.new(name, 'CURVE'); cu.dimensions = '3D'; cu.bevel_depth = 1.0; cu.bevel_resolution = 3; cu.use_fill_caps = True
    sp = cu.splines.new('NURBS'); sp.points.add(len(pts) - 1)
    for p, c, r in zip(sp.points, pts, radii):
        p.co = (c[0], c[1], c[2], 1.0); p.radius = r
    sp.use_endpoint_u = True; sp.order_u = min(4, len(pts)); sp.resolution_u = res
    cu.materials.append(mat); o = add(bpy.data.objects.new(name, cu))
    if parent:
        o.parent = parent
    return o


def strokes(name, groups, mat, n=46, seed=3, width=0.016, length=(0.42, 0.72), lift=(0.15, 0.9)):
    """fans of short brush strokes (pine needles, tufts of grass, reeds): groups = [(x, y, z, size), …]; all in one curve"""
    cu = bpy.data.curves.new(name, 'CURVE'); cu.dimensions = '3D'; cu.bevel_depth = width; cu.bevel_resolution = 1
    rnd = rng(seed)
    for cx, cy, cz, s in groups:
        for _ in range(n):
            a = rnd() * math.tau; up = lift[0] + rnd() * (lift[1] - lift[0])
            dx, dy, dz = math.cos(a) * (1 - up * 0.5), math.sin(a) * (1 - up * 0.5), up * 0.55
            ln = (length[0] + rnd() * (length[1] - length[0])) * s
            sp = cu.splines.new('POLY'); sp.points.add(1)
            sp.points[0].co = (cx, cy, cz, 1.0); sp.points[1].co = (cx + dx * ln, cy + dy * ln, cz + dz * ln, 1.0)
            sp.points[0].radius = 1.3; sp.points[1].radius = 0.3
    cu.materials.append(mat)
    return add(bpy.data.objects.new(name, cu))


def lathe(name, profile, mat, seg=56, sy=1.0):
    """a turned shape: profile = [(radius, z), …] spun about the vertical; sy squashes it front to back"""
    verts = []; faces = []; n = len(profile)
    for k in range(seg):
        a = math.tau * k / seg
        for r, z in profile:
            verts.append((r * math.cos(a), r * math.sin(a) * sy, z))
    for k in range(seg):
        k2 = (k + 1) % seg
        for i in range(n - 1):
            faces.append((k * n + i, k2 * n + i, k2 * n + i + 1, k * n + i + 1))
    me = bpy.data.meshes.new(name); me.from_pydata(verts, [], faces); me.update()
    bm = bmesh.new(); bm.from_mesh(me); bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5); bmesh.ops.recalc_face_normals(bm, faces=bm.faces); bm.to_mesh(me); bm.free()
    smooth(me); me.materials.append(mat)
    return add(bpy.data.objects.new(name, me))


def ball(name, loc, scale, mat, parent=None, rot=None):
    me = bpy.data.meshes.new(name); bm = bmesh.new(); bmesh.ops.create_uvsphere(bm, u_segments=32, v_segments=16, radius=1.0); bm.to_mesh(me); bm.free()
    smooth(me); me.materials.append(mat); o = add(bpy.data.objects.new(name, me)); o.location = loc; o.scale = scale
    if rot:
        o.rotation_euler = rot
    if parent:
        o.parent = parent
    return o


def quad(name, w, h, mat, loc, rot, parent=None):
    """an upright card w × h facing -Y, then turned by rot (radians)"""
    me = bpy.data.meshes.new(name); me.from_pydata([(-w / 2, 0, -h / 2), (w / 2, 0, -h / 2), (w / 2, 0, h / 2), (-w / 2, 0, h / 2)], [], [(0, 1, 2, 3)]); me.update()
    me.materials.append(mat); o = add(bpy.data.objects.new(name, me)); o.location = loc; o.rotation_euler = rot
    if parent:
        o.parent = parent
    return o


def disc(name, radius, mat, loc, segments=128):
    """a flat round card facing -Y (a sun, a moon)"""
    me = bpy.data.meshes.new(name); bm = bmesh.new(); bmesh.ops.create_circle(bm, cap_ends=True, segments=segments, radius=radius); bm.to_mesh(me); bm.free()
    me.materials.append(mat); o = add(bpy.data.objects.new(name, me)); o.location = loc; o.rotation_euler = (math.radians(90), 0, 0)
    return o


def mirror(objs, z, mat=None):
    """reflections without ray tracing: a copy of each (unparented) object flipped about the level z, in a paler material if given.
    Put the water's surface (a pale, part-transparent sheet, or nothing) just above z; the copies sit under it."""
    out = []
    for o in objs:
        c = o.copy(); c.data = o.data.copy() if mat else o.data
        if mat:
            c.data.materials.clear(); c.data.materials.append(mat)
        c.name = o.name + '-refl'; add(c)
        c.scale = (o.scale.x, o.scale.y, -o.scale.z); c.location = (o.location.x, o.location.y, 2 * z - o.location.z)
        out.append(c)
    return out


