def sunlight(elevation=32.0, azimuth=-62.0, energy=3.2, shadow=False):
    """the one light: elevation above the horizon, azimuth = where it comes FROM, degrees from +Y toward +X.
    It casts no shadows unless asked: the renderer fits its shadow maps to the camera's range, so a slab (a narrow range) gets
    sharper, darker shadows than a still of the whole scene, and the layers stop matching the still. The ink shader shades by
    which way a surface faces and by its crevices; it does not need cast shadows."""
    sl = bpy.data.lights.new('sunlight', 'SUN'); sl.energy = energy; sl.angle = math.radians(3); sl.use_shadow = shadow
    so = add(bpy.data.objects.new('sunlight', sl)); so.rotation_euler = (math.radians(90 - elevation), 0, math.radians(azimuth))
    return so


def camera(location, aim, over=(1.25, 1.25), focus=None, fstop=5.6):
    """the camera stands at `location` looking at `aim`. The frame is what a 35 mm lens sees (1920 × 1080); in layers mode the
    picture is drawn wider and taller by over = (x, y) so the layers have room to slide when the page moves the camera."""
    ox, oy = over if WIDE else (1.0, 1.0)
    STATE['over'] = (ox, oy)
    scene.render.resolution_x = int(round(FRAME_W * ox * RS)); scene.render.resolution_y = int(round(FRAME_H * oy * RS)); scene.render.resolution_percentage = 100
    cam = bpy.data.cameras.new('cam'); cam.sensor_fit = 'HORIZONTAL'; cam.lens = FOCAL_MM / ox; cam.sensor_width = SENSOR_MM; cam.clip_start = 0.1; cam.clip_end = 3000
    co = add(bpy.data.objects.new('cam', cam)); co.location = location
    co.rotation_euler = (Vector(aim) - Vector(location)).to_track_quat('-Z', 'Y').to_euler()
    if focus:
        cam.dof.use_dof = True; cam.dof.focus_distance = focus; cam.dof.aperture_fstop = fstop
    scene.camera = co; STATE['cam'] = cam; STATE['camobj'] = co
    return co


def anchor(name, point, size=None):
    """remember a point of the set; finish() writes where it lands in the frame (pixels) and how far it is, for the page to use.
    size: a length in scene units at that point (a radius, a height) — written as `r`, in frame pixels"""
    ANCHORS[name] = (point, size)             # a point, or an object (its origin is read when the picture is rendered)


def actor(name, root, exclude=(), pivot=None):
    """`root` and everything parented under it (except what hangs under `exclude`) is rendered on its own, crisp (no painterly
    pass). pivot: the point the page turns this part about (a shoulder) — a world point, or an object (read at render time,
    so you may still move or turn the character after this call)."""
    ACTORS.append((name, root, tuple(exclude), pivot))


