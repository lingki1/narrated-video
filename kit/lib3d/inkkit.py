def rng(seed):
    """a small repeatable random source: r() → 0…1"""
    state = [seed * 2654435761 % 4294967296 or 1]
    def r():
        state[0] = (1103515245 * state[0] + 12345) % 2147483648
        return state[0] / 2147483648
    return r


