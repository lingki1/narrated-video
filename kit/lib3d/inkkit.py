# The 3D ink-wash kit: everything a scene script needs to build a picture by script and render it headless (EEVEE).
# A scene is a short file that starts with `from inkkit import *`, builds its set, and ends with finish(slabs):
#   blender -b --factory-startup -P <scene>.py -- <out> [key=value …]        (tools/shot3d.py runs this for you)
#   mode=still (default)  one PNG of the frame as the camera stands (wide=1: with the overscan the layers are drawn with)
#   mode=layers           the picture cut into slabs by distance, each a PNG with alpha (<out> is a folder prefix): solids and mist,
#                         banks of cloud on their own, every actor on its own; plus layers.json (how far each slab is, where the
#                         anchors land in the frame). A web page stacks them and moves them (lib/plates.js): parallax, drift, acting.
#   keys: px=1 (rendered pixels per pixel of the 1920×1080 frame; tools/shot3d.py asks for 1.5 in layers)  samples=48  fog=1|0  post=1|0  kuw=3.2  edge=0.85  clouds=1 (banks of cloud on layers of their own)
#   A scene that ends in fly(pose, seconds) instead of finish() renders a camera move frame by frame (tools/shot3d.py … fly):
#   the one thing layers cannot do is fly around what they show. How to use all this: the skill's references/3d.md.
# Ink is a shader, not a texture. How much ink a point gets = which side faces the sun + what sits in a crevice + how near the
# summit + a dark edge where the surface turns away from the eye + streaks and blots of noise; then thinned by distance.
# Mist is a real volume that converges on the exact paper colour, so "left blank" in the picture is blank paper.
# Nothing here comes from anyone's artwork; every mesh is generated by code.
